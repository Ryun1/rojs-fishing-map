"""Write data/sst-normal.json: the normal sea temperature around Pico for each day of the year.

Source: docs/research/data/oisst_clim_1991_2020.json (built by
docs/research/scripts/clim.py from NOAA OISST v2.1, 1991-2020, 11-day running
mean, six 0.25-degree cells around Pico). The cells differ by under 0.2 C, so
the app uses their mean, one value per day of year (1..365), to one decimal.
The app compares the forecast sea temperature with it: only a difference of
about 1 C or more changes a species score.

Usage (from the repository root): python3 -I tools/sst_normal.py
Then bump CACHE in sw.js.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs", "research", "data", "oisst_clim_1991_2020.json")
OUT = os.path.join(ROOT, "data", "sst-normal.json")


def main():
    src = json.load(open(SRC, encoding="utf-8"))
    cells = list(src["cells"].values())
    days = [round(sum(c[i] for c in cells) / len(cells), 1) for i in range(365)]
    out = {
        "_about": "Normal sea surface temperature around Pico by day of year (index 0 = 1 January; 31 December in a leap year uses the last value), deg C. "
                  "Mean of the six NOAA OISST v2.1 cells around Pico, 1991-2020, 11-day running mean. Generated by tools/sst_normal.py.",
        "days": days,
    }
    with open(OUT, "w", encoding="utf-8") as f:
        f.write('{"_about": ' + json.dumps(out["_about"]) + ',\n "days": ' + json.dumps(days, separators=(",", ":")) + "}\n")
    print(f"{len(days)} days, {min(days)} to {max(days)} C")


if __name__ == "__main__":
    main()
